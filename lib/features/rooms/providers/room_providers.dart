import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:supabase_flutter/supabase_flutter.dart';
import '../../../data/models/property.dart';
import '../../../data/models/room.dart';
import '../../../data/repositories/property_repo.dart';
import '../../../data/repositories/resident_repo.dart';
import '../../../data/repositories/room_repo.dart';

// Repository Providers
final propertyRepoProvider = Provider<PropertyRepo>((ref) => PropertyRepo());
final roomRepoProvider = Provider<RoomRepo>((ref) => RoomRepo());
final residentRepoProvider = Provider<ResidentRepo>((ref) => ResidentRepo());

// Selected Property Provider
class SelectedPropertyNotifier extends Notifier<String?> {
  @override
  String? build() => null;

  void select(String? propertyId) {
    state = propertyId;
  }
}

final selectedPropertyIdProvider =
    NotifierProvider<SelectedPropertyNotifier, String?>(SelectedPropertyNotifier.new);

// Vacancy Filter Provider: false = All, true = Vacant Only
class VacancyFilterNotifier extends Notifier<bool> {
  @override
  bool build() => false;

  void toggle() {
    state = !state;
  }

  void setFilter(bool vacantOnly) {
    state = vacantOnly;
  }
}

final vacancyFilterProvider =
    NotifierProvider<VacancyFilterNotifier, bool>(VacancyFilterNotifier.new);

// Properties List AsyncNotifier
class PropertiesNotifier extends AsyncNotifier<List<Property>> {
  @override
  Future<List<Property>> build() async {
    final repo = ref.watch(propertyRepoProvider);
    final list = await repo.getProperties(activeOnly: true);
    
    // Auto-select the first property if none currently selected
    final currentSelected = ref.read(selectedPropertyIdProvider);
    if ((currentSelected == null || !list.any((p) => p.id == currentSelected)) && list.isNotEmpty) {
      ref.read(selectedPropertyIdProvider.notifier).select(list.first.id);
    }
    return list;
  }

  Future<Property> addProperty({
    required String name,
    String? address,
    String? city,
  }) async {
    final repo = ref.read(propertyRepoProvider);
    final newProp = Property(
      id: '', // generated by DB
      ownerId: '', // set by RLS
      name: name.trim(),
      address: address?.trim().isEmpty == true ? null : address?.trim(),
      city: city?.trim().isEmpty == true ? null : city?.trim(),
      createdAt: DateTime.now(),
    );

    final created = await repo.createProperty(newProp);
    ref.invalidateSelf();
    ref.read(selectedPropertyIdProvider.notifier).select(created.id);
    return created;
  }

  Future<Property> updateProperty(Property property) async {
    final repo = ref.read(propertyRepoProvider);
    final updated = await repo.updateProperty(property);
    ref.invalidateSelf();
    return updated;
  }

  Future<void> archiveProperty(String propertyId) async {
    final repo = ref.read(propertyRepoProvider);
    await repo.archiveProperty(propertyId);
    ref.invalidateSelf();
    ref.read(selectedPropertyIdProvider.notifier).select(null);
  }
}

final propertiesProvider =
    AsyncNotifierProvider<PropertiesNotifier, List<Property>>(PropertiesNotifier.new);

// Room Occupancy Mapping Provider: Map<roomId, occupiedCount>
final roomOccupancyProvider = FutureProvider<Map<String, int>>((ref) async {
  final residentRepo = ref.watch(residentRepoProvider);
  final residents = await residentRepo.getResidents(activeOnly: true);

  final Map<String, int> occupancyMap = {};
  for (final resident in residents) {
    if (resident.roomId != null && resident.roomId!.isNotEmpty) {
      occupancyMap[resident.roomId!] = (occupancyMap[resident.roomId!] ?? 0) + 1;
    }
  }
  return occupancyMap;
});

// Rooms List AsyncNotifier for selected property
class RoomsNotifier extends AsyncNotifier<List<Room>> {
  @override
  Future<List<Room>> build() async {
    final selectedPropId = ref.watch(selectedPropertyIdProvider);
    final repo = ref.watch(roomRepoProvider);

    if (selectedPropId == null) {
      return repo.getAllRooms(activeOnly: true);
    }
    return repo.getRooms(selectedPropId, activeOnly: true);
  }

  Future<Room> addRoom({
    required String propertyId,
    required String roomNumber,
    String? floor,
    required int capacity,
    required double defaultRent,
    String? notes,
  }) async {
    final repo = ref.read(roomRepoProvider);

    final newRoom = Room(
      id: '',
      ownerId: '',
      propertyId: propertyId,
      roomNumber: roomNumber.trim(),
      floor: floor?.trim().isEmpty == true ? null : floor?.trim(),
      capacity: capacity,
      defaultRent: defaultRent,
      notes: notes?.trim().isEmpty == true ? null : notes?.trim(),
      createdAt: DateTime.now(),
    );

    try {
      final created = await repo.createRoom(newRoom);
      ref.invalidateSelf();
      return created;
    } on PostgrestException catch (e) {
      if (e.code == '23505' || e.message.contains('unique') || e.message.contains('room_number')) {
        throw Exception('Room "$roomNumber" already exists in this property.');
      }
      rethrow;
    }
  }

  Future<Room> updateRoom(Room room) async {
    final repo = ref.read(roomRepoProvider);
    try {
      final updated = await repo.updateRoom(room);
      ref.invalidateSelf();
      return updated;
    } on PostgrestException catch (e) {
      if (e.code == '23505' || e.message.contains('unique') || e.message.contains('room_number')) {
        throw Exception('Room "${room.roomNumber}" already exists in this property.');
      }
      rethrow;
    }
  }
}

final roomsProvider =
    AsyncNotifierProvider<RoomsNotifier, List<Room>>(RoomsNotifier.new);

// Filtered Rooms Provider
final filteredRoomsProvider = Provider<AsyncValue<List<Room>>>((ref) {
  final roomsAsync = ref.watch(roomsProvider);
  final occupancyAsync = ref.watch(roomOccupancyProvider);
  final vacantOnly = ref.watch(vacancyFilterProvider);

  return roomsAsync.whenData((rooms) {
    if (!vacantOnly) return rooms;

    final occupancy = occupancyAsync.value ?? {};
    return rooms.where((room) {
      final occupied = occupancy[room.id] ?? 0;
      final freeBeds = room.capacity - occupied;
      return freeBeds > 0;
    }).toList();
  });
});
